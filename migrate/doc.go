// Package migrate is the database migration module for Gas apps. Its
// Service implements the core's gas.MigrationManager and gas.Service: other
// services register their migrations with it while they start, and the
// Worker applies whatever is pending once every service has started.
//
// # Wiring
//
// New returns a DI constructor that takes a gas.DatabaseProvider and
// returns *Service; register it under gas.MigrationManager, which is the type
// the Worker looks for. The constructor does not return an error, so it is
// not yet on the shape in CONVENTIONS.md (KI-004 in KNOWN_ISSUES.md). The
// package reads no configuration.
//
// # Lifecycle
//
// Starting the service picks the query adapter for the provider's driver
// ("postgres" and "pgx", "mysql", or "sqlite" and "sqlite3"; any other
// driver fails) and creates the __gas_migrations tracking table if it does
// not exist, under the start context, so the container's init deadline
// bounds it. Stopping it makes RunPending, Down, and CheckReady return an
// error.
//
// # Registering
//
// Register and RegisterSlice add gas.Migration values owned by a service.
// RegisterFS reads them from an fs.FS: every file ending in .up.sql is a
// migration, its version is the file name up to the first underscore and
// its description the rest with underscores turned into spaces, and a
// matching .down.sql file is required.
//
// # Applying and rolling back
//
// RunPending applies, in version order, every registered migration whose
// version is not in the tracking table. Versions are compared as strings,
// so they need a fixed width (a timestamp, for example) to sort as
// numbers. Each migration's up SQL and its tracking row commit in one
// transaction. When either fails, the transaction rolls back and the
// version is recorded as dirty; while any version is dirty, RunPending,
// Down, and CheckReady return an error wrapping ErrDirty that names the
// dirty versions, and the package offers no call that clears the mark
// (KI-020). Two services registering the same version is an error; one
// service registering it twice is not caught until it marks the version
// dirty (KI-021).
//
// Down reverts the n highest versions in the tracking table, highest first,
// and runs nothing while any version is dirty, since a dirty version's up
// SQL was rolled back and its down SQL would act on a schema it never
// changed. For each it runs the down SQL and deletes the tracking row in
// one transaction, so a failure leaves both the schema and the row as they
// were and returns the error, without marking the version dirty. Every
// reverted version must still be registered.
//
// On MySQL, DDL such as CREATE TABLE, DROP TABLE, and ALTER TABLE commits
// any open transaction implicitly, so a migration containing DDL is not
// atomic with its tracking row in either direction: a failure after the
// DDL leaves the schema changed whatever the tracking table says.
//
// CheckReady fails while any version is dirty or any registered migration
// has not been applied. Each tracking row also records the version of this
// module and of the module that owns the migration, read from the binary's
// build information.
//
// # Dialects
//
// The tracking queries are generated by sqlc for PostgreSQL, MySQL, and
// SQLite under db/; adapters map each dialect's generated types to one
// internal interface.
//
// See the module README for usage examples and design rationale.
//
