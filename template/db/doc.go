// Package db is the database-backed template store. Its Store implements
// gas.TemplateProvider and gas.Service, and keeps templates in the
// __gas_templates table, scoped by a namespace so several stores can share
// the table.
//
// # Wiring
//
// NewStore returns a DI constructor that takes a gas.DatabaseProvider, a
// gas.Logger, and a gas.MigrationManager, and returns *Store and an error,
// which is always nil; register it under gas.TemplateProvider.
// WithNamespace sets the namespace, "default" when not given. The package
// reads no configuration.
//
// # Lifecycle
//
// Starting the store picks the query adapter for the provider's driver
// ("postgres" and "pgx", "mysql", or "sqlite" and "sqlite3"; any other
// driver fails) and registers the migration that creates the table with the
// MigrationManager, which applies it after every service has started, so
// on a fresh database the table does not exist while services are still
// starting. Write templates into the store once startup has finished, for
// example from a ready function registered with gas.WithReadyFunc, which
// runs after migrations are applied, not from another service's Init.
// Every store on one driver registers an identical
// migration under the same service name, which gas/migrate applies once,
// so several stores can share a database. Stopping it does nothing.
//
// # Behavior
//
// Get returns template.ErrTemplateNotFound for a name with no row in the
// namespace. Register upserts by namespace and name, and RegisterFS upserts
// every .html file of an fs.FS. Exists and Delete are additional methods;
// Delete returns template.ErrTemplateNotFound when no row was removed. Both
// run on context.Background() rather than taking a context. Database
// errors are wrapped with the operation and, where there is one, the
// template name.
//
// The queries are generated by sqlc for each dialect in the postgres,
// mysql, and sqlite directories, and adapters map them to one internal
// interface.
//
